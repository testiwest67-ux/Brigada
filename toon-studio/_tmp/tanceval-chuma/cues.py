# Звуковая схема «Танцевальная чума 1518» → src/tanceval/sound.cues.json (для scripts/sfx.py).
# Только тональный звук (аккорды-подложки, глухие удары, нотки), без шумов. Под голосом всё приглушается.
import json, os

D = os.path.dirname(os.path.abspath(__file__))
CH = [0, 30, 62, 107, 130, 163, 195, 235, 262, 318]          # первые фразы глав (0-based)
CHORDS = [
    [55, 82.41, 110, 130.81],       # 0 крючок — ля минор, тревожно
    [65.41, 98, 130.81, 155.56],    # 1 город на краю
    [58.27, 87.31, 116.54, 138.59], # 2 первая
    [51.91, 77.78, 103.83, 123.47], # 3 зараза — темнее
    [55, 82.41, 110, 138.59],       # 4 лекарство хуже болезни
    [61.74, 92.5, 123.47, 146.83],  # 5 святой Вит — светлее к развязке
    [49, 73.42, 98, 116.54],        # 6 это уже было — самое тёмное
    [51.91, 77.78, 103.83, 123.47], # 7 сколько умерло
    [58.27, 87.31, 116.54, 146.83], # 8 версии
    [55, 82.41, 110, 130.81],       # 9 финал
]
pads = []
for i, c in enumerate(CH):
    t0 = 0 if i == 0 else f'line:{c}-0.5'
    t1 = f'line:{CH[i + 1]}' if i + 1 < len(CH) else 'end'
    pads.append({'t0': t0, 't1': t1, 'notes': CHORDS[i], 'gain': 0.06 if i in (3, 6, 7) else 0.07, 'attack': 2.5, 'release': 2})

# Акценты ставим В ПАУЗУ перед фразой (сразу после конца предыдущей), чтобы не перекрывать слова:
# правило канала — под словами фон минимум на 15 дБ тише голоса.
V = json.load(open(os.path.join(D, '..', '..', 'public', 'tanceval-chuma', 'voice.json'), encoding='utf-8'))['lines']
def gap(ln):  # (время начала паузы перед фразой ln, длина паузы)
    a = V[ln - 1]['end'] + 0.04 if ln else 0.0
    return round(a, 3), V[ln]['start'] - a

# удар на каждый титр главы (пауза 8 с)
ev = [{'type': 'thump', 't': gap(c)[0] + 0.3, 'gain': 0.22, 'f0': 70, 'f1': 40} for c in CH[1:]]

# «барабан на помосте»: мерный глухой пульс там, где в кадре музыка и толпа (тихо, ниже голоса)
def drum(a, b, step=0.75, gain=0.03):
    return [{'type': 'thump', 't': f'line:{a}+{k * step:.2f}', 'gain': gain, 'f0': 95, 'f1': 55} for k in range(int(b / step))]

ev += drum(2, 14)        # крючок: помост, барабаны (≈14 с)
ev += drum(147, 10)      # «нанимает музыкантов…»
ev += drum(152, 9, 0.6)  # «целое представление… музыка гремит»

# акценты на сильных фразах
for ln in [12, 18, 22, 57, 106, 117, 126, 151, 161, 166, 187, 209, 223, 236, 249, 261, 290]:
    t, g = gap(ln)
    ev.append({'type': 'thump', 't': t, 'gain': (0.1 if ln in (106, 187) else 0.16) if g >= 0.35 else 0.06, 'f0': 80, 'f1': 45})
# нотки и «проезды» длиннее удара: громко только если пауза длинная
for ln, e in [(54, {'type': 'notes', 'notes': [220, 261.63, 329.63], 'step': 0.12}),          # святой Вит
              (84, {'type': 'glide', 'f0': 330, 'f1': 165}),                                  # «она не слышит»
              (177, {'type': 'notes', 'notes': [392, 493.88, 587.33], 'step': 0.1}),          # красные башмаки
              (187, {'type': 'notes', 'notes': [329.63, 392, 493.88, 659.25], 'step': 0.08}), # «это помогает»
              (209, {'type': 'glide', 'f0': 260, 'f1': 80}),                                  # мост рушится
              (289, {'type': 'glide', 'f0': 180, 'f1': 540}),                                 # транс
              (323, {'type': 'notes', 'notes': [329.63, 392, 493.88], 'step': 0.12})]:        # три версии
    t, g = gap(ln)
    e = dict(e, t=t, gain=(0.04 if ln == 187 else 0.08) if g >= 0.6 else 0.025)
    if e['type'] == 'glide': e['dur'] = round(max(0.3, g), 2)
    else: e['decay'] = round(max(0.3, g), 2)
    ev.append(e)
json.dump({'total': 'auto', 'pads': pads, 'events': ev, 'duck': {'db': 10, 'music_db': 14}},
          open(os.path.join(D, '..', '..', 'src', 'tanceval', 'sound.cues.json'), 'w', encoding='utf-8'), indent=1)
print('подложек', len(pads), 'событий', len(ev))
