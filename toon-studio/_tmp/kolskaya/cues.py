# Звуковая схема «Кольская сверхглубокая» → src/tanceval/sound.cues.json (для scripts/sfx.py).
# Только тональный звук (аккорды-подложки, глухие удары, нотки), без шумов. Под голосом всё приглушается.
import json, os

D = os.path.dirname(os.path.abspath(__file__))
CH = [0, 33, 62, 93, 111, 140, 176, 209, 237, 278]          # первые фразы глав (0-based)
CHORDS = [
    [55, 82.41, 110, 130.81],       # 0 крючок — ля минор, холодно
    [65.41, 98, 130.81, 164.81],    # 1 гонка в недра — светлее, азарт
    [58.27, 87.31, 116.54, 146.83], # 2 город на краю
    [65.41, 98, 130.81, 155.56],    # 3 рекорд
    [51.91, 77.78, 103.83, 123.47], # 4 обрыв — темнее
    [61.74, 92.5, 123.47, 146.83],  # 5 что нашли — загадка
    [49, 73.42, 98, 116.54],        # 6 жар — самое тёмное
    [46.25, 69.3, 92.5, 110],       # 7 колодец в ад — жуть
    [55, 82.41, 110, 138.59],       # 8 кто придумал — разрядка
    [55, 82.41, 110, 130.81],       # 9 финал
]
pads = []
for i, c in enumerate(CH):
    t0 = 0 if i == 0 else f'line:{c}-0.5'
    t1 = f'line:{CH[i + 1]}' if i + 1 < len(CH) else 'end'
    pads.append({'t0': t0, 't1': t1, 'notes': CHORDS[i], 'gain': 0.03 if i == 9 else 0.045 if i in (4, 6, 7) else 0.055, 'attack': 2.5, 'release': 2})

# Акценты ставим В ПАУЗУ перед фразой (сразу после конца предыдущей), чтобы не перекрывать слова:
# правило канала — под словами фон минимум на 15 дБ тише голоса.
V = json.load(open(os.path.join(D, '..', '..', 'public', 'kolskaya', 'voice.json'), encoding='utf-8'))['lines']
def gap(ln):  # (время начала паузы перед фразой ln, длина паузы)
    a = V[ln - 1]['end'] + 0.04 if ln else 0.0
    return round(a, 3), V[ln]['start'] - a

# удар на каждый титр главы (пауза 8 с)
ev = [{'type': 'thump', 't': gap(c)[0] + 0.3, 'gain': 0.22, 'f0': 70, 'f1': 40} for c in CH[1:]]

# «бур»: мерный глухой пульс там, где в кадре работает буровая (тихо, ниже голоса)
def drum(a, b, step=0.9, gain=0.03):
    return [{'type': 'thump', 't': f'line:{a}+{k * step:.2f}', 'gain': gain, 'f0': 60, 'f1': 38} for k in range(int(b / step))]

ev += drum(77, 12)       # колонна из труб, долото грызёт камень
ev += drum(126, 8, 1.1)  # бурят в обход, метр за метром

# акценты на сильных фразах
for ln in [8, 11, 49, 116, 131, 149, 161, 180, 196, 206, 214, 219, 222, 259, 291, 304]:
    t, g = gap(ln)
    ev.append({'type': 'thump', 't': t, 'gain': (0.05 if ln in (15, 305) else 0.1 if ln in (131, 206, 49, 219) else 0.16) if g >= 0.35 else 0.06, 'f0': 80, 'f1': 45})
# нотки и «проезды»: громко только если пауза длинная
for ln, e in [(10, {'type': 'glide', 'f0': 220, 'f1': 70}),                                  # вниз на 12 км
              (94, {'type': 'notes', 'notes': [329.63, 392, 493.88], 'step': 0.1}),          # рекорд 1979
              (114, {'type': 'glide', 'f0': 180, 'f1': 420}),                                # «стала лёгкой»
              (166, {'type': 'notes', 'notes': [392, 493.88, 587.33], 'step': 0.12}),        # планктон
              (184, {'type': 'glide', 'f0': 260, 'f1': 90}),                                 # как пластик
              (226, {'type': 'glide', 'f0': 160, 'f1': 520}),                                # «запись»
              (231, {'type': 'notes', 'notes': [329.63, 392, 493.88], 'step': 0.12}),        # сравним
              (305, {'type': 'notes', 'notes': [329.63, 392, 493.88], 'step': 0.12})]:       # три версии
    t, g = gap(ln)
    e = dict(e, t=t, gain=0.08 if g >= 0.6 else 0.025)
    if e['type'] == 'glide': e['dur'] = round(max(0.3, g), 2)
    else: e['decay'] = round(max(0.3, g), 2)
    ev.append(e)
json.dump({'total': 'auto', 'pads': pads, 'events': ev, 'duck': {'db': 15, 'music_db': 15, 'smooth': 0.04}},
          open(os.path.join(D, '..', '..', 'src', 'kolskaya', 'sound.cues.json'), 'w', encoding='utf-8'), indent=1)
print('подложек', len(pads), 'событий', len(ev))
